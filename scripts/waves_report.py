"""Generate wave-planning evaluation report → reports/waves.md.

Compares three batching algorithms (FCFS, Seed+Savings, Aisle-Cluster) against the
historical wave record on the 10 busiest operational days.

Usage
-----
    python scripts/waves_report.py [--days N] [--operators N]

Options
-------
--days N        Number of busiest days to evaluate (default: 10).
--operators N   Number of pickers assumed available per day (default: 5).
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from warehouse_ai.config import load_config
from warehouse_ai.models.waves import evaluate_on_historical_days, plan_waves, replay_historical_waves

REPORTS_DIR = Path(__file__).resolve().parents[1] / "reports"
REPORTS_DIR.mkdir(exist_ok=True)


def _algo_label(algo: str) -> str:
    return {
        "fcfs": "FCFS",
        "seed_savings": "Seed+Savings",
        "aisle_cluster": "Aisle-Cluster",
    }.get(algo, algo)


def _delta_str(val: float) -> str:
    if val > 0:
        return f"+{val:.1f}%"
    return f"{val:.1f}%"


def main(n_days: int = 10, n_operators: int = 5) -> None:
    cfg = load_config()
    proc = Path(cfg.paths.data_processed)

    print(f"[waves_report] Loading processed data from {proc}")
    orders_df = pd.read_parquet(proc / "orders_clean.parquet")
    picks_df = pd.read_parquet(proc / "picks_clean.parquet")
    storage_df = pd.read_parquet(proc / "storage_long.parquet")
    locations_df = pd.read_parquet(proc / "locations.parquet")
    waves_df = pd.read_parquet(proc / "waves.parquet")

    print(f"[waves_report] Evaluating 3 algorithms on {n_days} busiest days ({n_operators} operators each) …")
    t0 = time.perf_counter()
    eval_df = evaluate_on_historical_days(
        n_sample_days=n_days,
        algorithms=["fcfs", "seed_savings", "aisle_cluster"],
        n_operators=n_operators,
        orders_df=orders_df,
        picks_df=picks_df,
        storage_df=storage_df,
        locations_df=locations_df,
        waves_df=waves_df,
    )
    elapsed = time.perf_counter() - t0
    print(f"[waves_report] Evaluation done in {elapsed:.1f}s — {len(eval_df)} rows")

    # ------------------------------------------------------------------
    # Aggregate summary per algorithm
    # ------------------------------------------------------------------
    summary = (
        eval_df.groupby("algorithm")
        .agg(
            n_days=("date", "nunique"),
            mean_waves_planned=("n_waves_planned", "mean"),
            mean_waves_historical=("n_waves_historical", "mean"),
            mean_travel_planned=("total_travel_planned", "mean"),
            mean_travel_historical=("total_travel_historical", "mean"),
            mean_hours_planned=("total_hours_planned", "mean"),
            mean_hours_historical=("total_hours_historical", "mean"),
            mean_travel_delta_pct=("travel_delta_pct", "mean"),
            mean_hours_delta_pct=("hours_delta_pct", "mean"),
        )
        .reset_index()
    )

    # ------------------------------------------------------------------
    # Sample plan_waves() for one busiest day to show ordered pick lists
    # ------------------------------------------------------------------
    busiest_date = (
        orders_df.groupby(orders_df["date"].astype(str))["qty"].sum().idxmax()
    )
    print(f"[waves_report] Generating sample plan for busiest day: {busiest_date}")
    day_orders = orders_df[orders_df["date"].astype(str) == busiest_date].copy()

    sample_plans: dict[str, list] = {}
    for algo in ["fcfs", "seed_savings"]:
        import numpy as np
        rng = np.random.default_rng(42)
        t_algo = time.perf_counter()
        plans = plan_waves(
            orders_df=day_orders,
            n_operators=n_operators,
            algorithm=algo,
            storage_df=storage_df,
            locations_df=locations_df,
            rng=rng,
        )
        print(f"  {algo}: {len(plans)} waves in {time.perf_counter()-t_algo:.1f}s")
        sample_plans[algo] = plans

    hist_plans = replay_historical_waves(waves_df=waves_df, picks_df=picks_df, date=busiest_date)

    # ------------------------------------------------------------------
    # Build report markdown
    # ------------------------------------------------------------------
    lines: list[str] = [
        "# Wave Planning & Batching Evaluation Report",
        "",
        "> Generated by `scripts/waves_report.py`  ",
        f"> Sample: **{n_days} busiest days**, {n_operators} operators/day  ",
        f"> Runtime: {elapsed:.1f}s",
        "",
        "---",
        "",
        "## 1. Algorithm Summary (averaged over sample days)",
        "",
        "| Algorithm | Days | Waves (planned) | Waves (hist.) | Travel (planned) | Travel (hist.) | Travel Δ | Hours (planned) | Hours Δ |",
        "|-----------|-----:|---------------:|-------------:|----------------:|---------------:|---------:|----------------:|--------:|",
    ]
    for _, row in summary.iterrows():
        lines.append(
            f"| {_algo_label(row['algorithm'])} "
            f"| {int(row['n_days'])} "
            f"| {row['mean_waves_planned']:.0f} "
            f"| {row['mean_waves_historical']:.0f} "
            f"| {row['mean_travel_planned']:,.0f} "
            f"| {row['mean_travel_historical']:,.0f} "
            f"| {_delta_str(row['mean_travel_delta_pct'])} "
            f"| {row['mean_hours_planned']:.2f} h "
            f"| {_delta_str(row['mean_hours_delta_pct'])} |"
        )

    lines += [
        "",
        "> **Note**: Travel in raw coordinate units (AS-IS random storage layout).",
        "> Historical waves use recorded travel_dist; planned waves use S-Shape route_length.",
        "> Hours estimated via the calibrated LaborModel (k = 1.5853).",
        "",
        "---",
        "",
        "## 2. Per-Day Detail",
        "",
        "| Date | Algorithm | Waves (P) | Waves (H) | Travel (P) | Travel (H) | Travel Δ | Hours (P) | Hours (H) | Hours Δ |",
        "|------|-----------|----------:|----------:|-----------:|-----------:|---------:|----------:|----------:|--------:|",
    ]
    for _, row in eval_df.sort_values(["date", "algorithm"]).iterrows():
        lines.append(
            f"| {row['date']} "
            f"| {_algo_label(row['algorithm'])} "
            f"| {int(row['n_waves_planned'])} "
            f"| {int(row['n_waves_historical'])} "
            f"| {row['total_travel_planned']:,.0f} "
            f"| {row['total_travel_historical']:,.0f} "
            f"| {_delta_str(row['travel_delta_pct'])} "
            f"| {row['total_hours_planned']:.2f} "
            f"| {row['total_hours_historical']:.2f} "
            f"| {_delta_str(row['hours_delta_pct'])} |"
        )

    # Sample wave plans for busiest day
    lines += [
        "",
        "---",
        "",
        f"## 3. Sample Wave Plans — Busiest Day ({busiest_date})",
        "",
        f"Historical: **{len(hist_plans)} waves** | "
        f"FCFS: **{len(sample_plans.get('fcfs', []))} waves** | "
        f"Seed+Savings: **{len(sample_plans.get('seed_savings', []))} waves**",
        "",
        "### FCFS — First 5 waves",
        "",
        "| Wave | Orders | Units | Locs | Aisles | Est. Travel | Est. Time | Operator |",
        "|-----:|-------:|------:|-----:|-------:|------------:|----------:|----------|",
    ]
    for p in sample_plans.get("fcfs", [])[:5]:
        lines.append(
            f"| {p.wave_index} | {p.n_orders} | {p.n_units} "
            f"| {p.n_distinct_locations} | {p.n_aisles} "
            f"| {p.estimated_travel:,.0f} | {p.estimated_time_s/60:.1f} min | {p.operator} |"
        )

    lines += [
        "",
        "### Seed+Savings — First 5 waves",
        "",
        "| Wave | Orders | Units | Locs | Aisles | Est. Travel | Est. Time | Operator |",
        "|-----:|-------:|------:|-----:|-------:|------------:|----------:|----------|",
    ]
    for p in sample_plans.get("seed_savings", [])[:5]:
        lines.append(
            f"| {p.wave_index} | {p.n_orders} | {p.n_units} "
            f"| {p.n_distinct_locations} | {p.n_aisles} "
            f"| {p.estimated_travel:,.0f} | {p.estimated_time_s/60:.1f} min | {p.operator} |"
        )

    # Operator workload summary
    lines += [
        "",
        "---",
        "",
        "## 4. Operator Workload Balance (FCFS, Busiest Day)",
        "",
        "| Operator | Waves | Total Est. Hours |",
        "|----------|------:|-----------------:|",
    ]
    from collections import defaultdict
    op_summary: dict[str, dict] = defaultdict(lambda: {"waves": 0, "hours": 0.0})
    for p in sample_plans.get("fcfs", []):
        op_summary[p.operator]["waves"] += 1
        op_summary[p.operator]["hours"] += p.estimated_time_s / 3600.0
    for op, info in sorted(op_summary.items()):
        lines.append(f"| {op} | {info['waves']} | {info['hours']:.2f} |")

    lines += [
        "",
        "---",
        "",
        "## 5. Methodology",
        "",
        "- **Baseline (Historical)**: Waves replayed as-is from `waves.parquet`; travel = recorded `travel_dist`.",
        "- **FCFS**: Orders sorted by `created_at`, packed greedily into waves of ≤27 units and ≤24 orders.",
        "- **Seed+Savings**: Each wave seeded with the widest-footprint (most aisles) unassigned order;",
        "  remaining orders added by minimum marginal S-Shape route increase.",
        "- **Aisle-Cluster**: Orders represented as binary aisle-visit vectors; agglomerative cosine clustering",
        "  groups orders by geographic affinity; FCFS packs each cluster into sub-waves.",
        "- **Operator Assignment**: Longest-Processing-Time (LPT) greedy scheduler assigns waves to operators",
        "  to minimise makespan (max operator load) over a 7.5-hour shift.",
        "",
        "> **Caveat**: The comparison is directional only. Historical travel uses recorded values from pick logs;",
        "> planned travel uses S-Shape heuristic over the AS-IS random storage layout. SKU–location resolution",
        "> covers ~89.7% of order lines (random policy coverage); the remaining 10.3% are silently excluded.",
    ]

    report_path = REPORTS_DIR / "waves.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[waves_report] Written → {report_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate wave planning report.")
    parser.add_argument("--days", type=int, default=10)
    parser.add_argument("--operators", type=int, default=5)
    args = parser.parse_args()
    main(n_days=args.days, n_operators=args.operators)

