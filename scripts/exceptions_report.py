"""Generate operational anomaly & exceptions report → reports/exceptions.md.

Runs rule-based and statistical anomaly detection across:
- Short / over picks
- Location policy mismatches
- Unknown master data
- Daily volume demand breaches
- Operator productivity outliers
- IsolationForest statistical wave anomalies

Outputs detailed counts, severity breakdowns, and actionable remediation tasks.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import pandas as pd

# Ensure src is in pythonpath
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from warehouse_ai.models.anomaly import exceptions_to_dataframe, scan_all_exceptions

REPORTS_DIR = Path(__file__).resolve().parents[1] / "reports"
REPORTS_DIR.mkdir(exist_ok=True)


def _sev_emoji(sev: str) -> str:
    return {"HIGH": "🔴 High", "MEDIUM": "🟡 Medium", "LOW": "🟢 Low"}.get(sev, sev)


def main() -> None:
    print("[exceptions_report] Running operational anomaly scanner across warehouse data...")
    t0 = time.perf_counter()
    records = scan_all_exceptions()
    elapsed = time.perf_counter() - t0
    print(f"[exceptions_report] Scanned {len(records):,} exceptions in {elapsed:.1f}s")

    df = exceptions_to_dataframe(records)

    # Aggregations
    type_counts = df["type"].value_counts()
    sev_counts = df["severity"].value_counts()

    lines: list[str] = [
        "# Warehouse Operational Exceptions & Anomaly Audit",
        "",
        "> Generated by `scripts/exceptions_report.py`  ",
        f"> Total exceptions detected: **{len(df):,}**  ",
        f"> Scan duration: **{elapsed:.1f}s**",
        "",
        "---",
        "",
        "## 1. Executive Summary & Severity Breakdown",
        "",
        "| Severity | Total Records | Share of Total | Primary Risk |",
        "|----------|--------------:|---------------:|--------------|",
    ]

    for sev in ["HIGH", "MEDIUM", "LOW"]:
        cnt = int(sev_counts.get(sev, 0))
        pct = (cnt / max(1, len(df))) * 100
        risk_map = {
            "HIGH": "Customer order fulfillment shortfalls / Unknown master data catalog gaps",
            "MEDIUM": "WMS slotting inventory drift / Operator productivity outliers",
            "LOW": "Bulk scanning variances / Minor routing anomalies",
        }
        lines.append(f"| {_sev_emoji(sev)} | {cnt:,} | {pct:.1f}% | {risk_map.get(sev, '')} |")

    lines += [
        "",
        "---",
        "",
        "## 2. Exceptions by Anomaly Category",
        "",
        "| Anomaly Type | Total Count | Default Severity | Core Suggested Action |",
        "|--------------|------------:|-----------------:|-----------------------|",
    ]

    action_summary = {
        "SHORT_PICK": "Cycle count forward bins & verify customer wave allocation",
        "OVER_PICK": "Audit wave packing station & log returned stock",
        "LOCATION_POLICY_MISMATCH": "Update active WMS slotting master for SKU / Physical bin check",
        "UNKNOWN_REFERENCE": "Register SKU reference in ERP / WMS master catalog",
        "UNKNOWN_LOCATION": "Add staging bay or coordinate to warehouse navigation graph",
        "DEMAND_SURGE_BREACH": "Authorize temporary flex labor & alert freight carriers",
        "DEMAND_DROP_BREACH": "Reallocate pickers to replenishment & cycle counting",
        "OPERATOR_PRODUCTIVITY_LOW": "Investigate handheld scanner battery / duty assignments",
        "OPERATOR_PRODUCTIVITY_HIGH": "Audit for bulk barcode scanning or multi-wave consolidation",
        "STATISTICAL_WAVE_ANOMALY": "Review wave batching parameters & tour routing sequence",
    }

    for anom_type, cnt in type_counts.items():
        sub = df[df["type"] == anom_type]
        top_sev = sub["severity"].mode().iloc[0] if not sub.empty else "MEDIUM"
        action = action_summary.get(anom_type, "Investigate warehouse operations")
        lines.append(f"| `{anom_type}` | {cnt:,} | {_sev_emoji(top_sev)} | {action} |")

    lines += [
        "",
        "---",
        "",
        "## 3. High-Priority Actionable Incidents (Top 25)",
        "",
        "| # | Type | Entity | Date | Severity | Evidence | Suggested Action |",
        "|---|------|--------|------|:--------:|----------|------------------|",
    ]

    # Prioritize HIGH severity, then sample diverse types
    high_priority = df[df["severity"] == "HIGH"]
    other_priority = df[df["severity"] != "HIGH"]
    top_examples = pd.concat([high_priority.head(15), other_priority.head(10)]).head(25)

    for i, (_, row) in enumerate(top_examples.iterrows(), 1):
        clean_ev = str(row["evidence"]).replace("|", "\\|")
        clean_act = str(row["suggested_action"]).replace("|", "\\|")
        lines.append(
            f"| {i} | `{row['type']}` | `{row['entity']}` | {row['date']} | "
            f"{_sev_emoji(row['severity'])} | {clean_ev} | {clean_act} |"
        )

    lines += [
        "",
        "---",
        "",
        "## 4. Remediation Workflow & Governance",
        "",
        "1. **Immediate Cycle Counting**: 22 unknown pick locations (e.g., `ZN-COR`, `RC-04`, `EX-01`) "
        "must be formalized in `Storage_Location.csv` or routed through standard center corridor nodes.",
        "2. **Catalog Audit Gate**: High-shortfall SKU references must be checked against Product.ABCCOD "
        "to resolve the 46.2% catalog ABC mismatch identified in Milestone 7.",
        "3. **Wave Batching Filter**: Statistical wave anomalies with travel > 10,000 units are clustered "
        "and split into two smaller waves to prevent cart overflow beyond 27 pairs.",
    ]

    out_path = REPORTS_DIR / "exceptions.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[exceptions_report] Written report → {out_path}")


if __name__ == "__main__":
    main()
