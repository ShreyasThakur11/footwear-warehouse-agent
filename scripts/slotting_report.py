"""Generate storage-policy comparison table and re-slotting proposals.

Runs all 4 empirical storage policies (random, class_based, dedicated, hybrid)
plus the Optimised-COI layout against the historical pick log, then writes
reports/slotting.md with a summary table and the top relocation proposals.

Usage
-----
    python scripts/slotting_report.py [--max-waves N]

Options
-------
--max-waves N   Limit simulation to N waves per policy (default: all waves).
                Use a small number (e.g. 200) for a quick smoke-test run.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import pandas as pd

# Ensure src is importable
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from warehouse_ai.config import load_config
from warehouse_ai.models.slotting import compare_all_policies, recommend_reslotting

REPORTS_DIR = Path(__file__).resolve().parents[1] / "reports"
REPORTS_DIR.mkdir(exist_ok=True)


def _effort_emoji(effort: str) -> str:
    return {"Low": "🟢 Low", "Medium": "🟡 Medium", "High": "🔴 High"}.get(effort, effort)


def main(max_waves: int | None = None) -> None:
    cfg = load_config()
    proc_dir = Path(cfg.paths.data_processed)

    print(f"[slotting_report] Loading processed data from {proc_dir}")
    picks_df = pd.read_parquet(proc_dir / "picks_clean.parquet")
    storage_df = pd.read_parquet(proc_dir / "storage_long.parquet")
    locations_df = pd.read_parquet(proc_dir / "locations.parquet")

    print(f"[slotting_report] Simulating all policies (max_waves={max_waves or 'ALL'}) …")
    t0 = time.perf_counter()
    sum_df, _ = compare_all_policies(
        picks_df=picks_df,
        storage_df=storage_df,
        locations_df=locations_df,
        max_waves=max_waves,
    )
    elapsed = time.perf_counter() - t0
    print(f"[slotting_report] Done in {elapsed:.1f}s")

    print("[slotting_report] Computing top-20 reslotting proposals …")
    moves = recommend_reslotting(
        baseline_policy="random",
        top_n=20,
        picks_df=picks_df,
        storage_df=storage_df,
        locations_df=locations_df,
    )

    # ------------------------------------------------------------------
    # Build report
    # ------------------------------------------------------------------
    lines: list[str] = [
        "# Storage Policy Simulation & Re-Slotting Report",
        "",
        "> Generated by `scripts/slotting_report.py`  ",
        f"> Simulation scope: **{int(sum_df['total_waves'].max())} waves** per policy  ",
        f"> Runtime: {elapsed:.1f}s",
        "",
        "---",
        "",
        "## 1. Policy Comparison",
        "",
        "| Policy | Waves | Total Picks | Mean Wave Travel (m) | Total Labor (h) | Travel ↓ vs Random | Labor ↓ vs Random |",
        "|--------|------:|------------:|---------------------:|----------------:|-------------------:|------------------:|",
    ]

    for _, row in sum_df.iterrows():
        tr = row["travel_reduction_pct"]
        lr = row["labor_reduction_pct"]
        tr_str = f"**{tr:+.1f}%**" if tr != 0.0 else "—"
        lr_str = f"**{lr:+.1f}%**" if lr != 0.0 else "—"
        lines.append(
            f"| `{row['policy_name']}` "
            f"| {int(row['total_waves']):,} "
            f"| {int(row['total_picks']):,} "
            f"| {row['mean_wave_travel']:.1f} "
            f"| {row['total_labor_hours']:.1f} "
            f"| {tr_str} "
            f"| {lr_str} |"
        )

    lines += [
        "",
        "> **Note**: Travel figures use Dijkstra shortest-path distances on the warehouse navigation graph.",
        "> Labor hours use the calibrated `LaborModel` (scale factor k = 1.5853).",
        "",
        "---",
        "",
        "## 2. Key Insight",
        "",
    ]

    # Find best policy
    best_row = sum_df.sort_values("travel_reduction_pct", ascending=False).iloc[0]
    lines += [
        f"The **`{best_row['policy_name']}`** policy delivers the largest travel reduction "
        f"(**{best_row['travel_reduction_pct']:+.1f}%**) and labor reduction "
        f"(**{best_row['labor_reduction_pct']:+.1f}%**) vs the random baseline,  ",
        f"cutting mean wave travel from "
        f"**{sum_df[sum_df['policy_name']=='random']['mean_wave_travel'].values[0]:.1f} m** "
        f"down to **{best_row['mean_wave_travel']:.1f} m**.",
        "",
        "---",
        "",
        "## 3. Top-20 Re-Slotting Proposals",
        "",
        "Proposals are sorted by **expected weekly round-trip travel saved**.",
        "",
        "| # | SKU-Size | From | To | Weekly Picks | Weekly Travel Saved (m) | Effort |",
        "|---|----------|------|----|-------------:|------------------------:|--------|",
    ]

    for i, m in enumerate(moves, 1):
        lines.append(
            f"| {i} "
            f"| `{m['sku_size']}` "
            f"| `{m['from_location']}` "
            f"| `{m['to_location']}` "
            f"| {m['weekly_picks']:.1f} "
            f"| {m['expected_travel_saved_per_week']:.1f} "
            f"| {_effort_emoji(m['move_effort'])} |"
        )

    lines += [
        "",
        "> **Move Effort Key**: 🟢 Low = hand-carry same aisle; 🟡 Medium = trolley across aisles; 🔴 High = forklift/upper tier.",
        "",
        "---",
        "",
        "## 4. Methodology",
        "",
        "- **Policy Simulator**: For each wave, all picks are mapped to the nearest available location holding",
        "  that SKU-size under the given storage policy using pre-computed Dijkstra distances.",
        "  Route length is computed with the S-Shape heuristic from/to depot `CC-01`.",
        "- **COI Layout**: SKU-sizes ranked by historical pick frequency; locations ranked by",
        "  `dist_depot + 300 × (level − 1)`. Top-frequency SKUs fill top-accessibility bins (≤18 slots/location).",
        "  Co-picked size runs are clustered into adjacent bins.",
        "- **Re-Slotting Proposals**: For each SKU-size, compare current random-policy location vs COI target.",
        "  Weekly travel saving = `(d_from − d_to) × 2 × weekly_picks`.",
    ]

    report_path = REPORTS_DIR / "slotting.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[slotting_report] Written → {report_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate slotting simulation report.")
    parser.add_argument("--max-waves", type=int, default=None, help="Limit waves per policy.")
    args = parser.parse_args()
    main(max_waves=args.max_waves)

